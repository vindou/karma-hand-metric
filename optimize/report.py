"""Aggregate every arm's results into optimize/runs/RESULTS_AUTO.md (regenerate any time; the hand-written technical report is optimize/runs/REPORT.md and includes this file as an appendix).

    python optimize/report.py
"""
from __future__ import annotations
import json, sys, csv
from pathlib import Path
import numpy as np
import yaml
REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
RUNS = REPO / "optimize" / "runs"
PUB = {r["robot"]: r for r in yaml.safe_load((REPO / "results/16_hand_batch/summary.yaml").read_text())["rows"]}


def jload(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def yload(p):
    p = Path(p)
    return yaml.safe_load(p.read_text()) if p.exists() else None


def run_row(name, label):
    best = jload(RUNS / name / "best.json"); meta = jload(RUNS / name / "meta.json"); fin = jload(RUNS / name / "final" / "summary.json")
    if not best:
        return None
    gens = meta.get("generations_done") if meta else None
    n_eval = sum(1 for _ in open(RUNS / name / "evals.jsonl")) if (RUNS / name / "evals.jsonl").exists() else None
    return {"run": name, "label": label, "gens": gens, "evals": n_eval, "proxy_obj": best["objective"],
            "proxy_T": best["result"]["karma_t"], "proxy_vox": best["result"]["top3_voxels"],
            "official_T": fin["KaRMA_T"] if fin else None, "official_R": fin["KaRMA_R"] if fin else None,
            "official_S": fin["KaRMA_S"] if fin else None, "official_vox": fin["n_voxels"] if fin else None,
            "L_ref_mm": fin["L_ref_mm"] if fin else round(best["result"]["l_ref_m"] * 1e3, 1),
            "backend": (fin or {}).get("backend", "–"),
            "ref_T": (jload(RUNS / name / "final_reference" / "summary.json") or {}).get("KaRMA_T"),
            "status": "scored" if fin else ("running/queued" if not (RUNS / name / "final.log").exists() else "scoring")}


def fmt(v, nd=4):
    if v is None: return "–"
    if isinstance(v, float): return f"{v:.{nd}f}"
    return str(v)


LABELS = [("T", "CPU pilot: 4+4, 150° cap, anthropomorphic start, T (reference backend, loop proxy)"),
          ("A1", "arm A: 4+4, 150° cap, anthropomorphic start, T"), ("A2", "arm A: restart, random start (seed 2)"),
          ("A3", "arm A: restart, random start (seed 3)"), ("D_R", "arm D: objective R"), ("D_TR", "arm D: objective T+R"),
          ("B_2x2", "arm B: 2+2 DOF"), ("B_3x3", "arm B: 3+3 DOF"), ("B_5x5", "arm B: 5+5 DOF"),
          ("C_cap45", "arm C: 90° total range cap"), ("C_cap60", "arm C: 120° cap"), ("C_cap90", "arm C: 180° cap")]


def main():
    out = []
    out.append("# KaRMA adversarial-optimization experiment: results\n")
    out.append("Regenerated by `python optimize/report.py`. Proxy = fast_eval (reduced seeds); official = karma.metric.compute_metric.\n")
    out.append("Published references (official): LEAP T=0.0969 R=0.304 S=0.448; Allegro T=0.0547 R=0.335 S=0.542.\n")

    # baseline
    b = jload(RUNS / "baseline" / "summary.json")
    if b:
        out.append(f"\n**Hand-drawn baseline (start of run T):** official T={b['KaRMA_T']}, R={b['KaRMA_R']}, S={b['KaRMA_S']}, "
                   f"{b['n_voxels']} voxels, L_ref {b['L_ref_mm']} mm.\n")

    out.append("\n## Optimization runs (arms A, B, C, D)\n")
    out.append("| run | condition | gens | evals | proxy obj | proxy T | proxy top voxels | official T | official R | official S | official voxels | L_ref mm | backend | ref-CPU T | status |")
    out.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    rows = []
    for name, label in LABELS:
        r = run_row(name, label)
        if r:
            rows.append(r)
            out.append(f"| {r['run']} | {r['label']} | {fmt(r['gens'])} | {fmt(r['evals'])} | {fmt(r['proxy_obj'])} | {fmt(r['proxy_T'])} | "
                       f"{r['proxy_vox']} | {fmt(r['official_T'])} | {fmt(r['official_R'])} | {fmt(r['official_S'])} | "
                       f"{fmt(r['official_vox'])} | {fmt(r['L_ref_mm'], 1)} | {r['backend']} | {fmt(r['ref_T'])} | {r['status']} |")

    # arm F
    out.append("\n## Arm F: L_ref variants on the 16 bundled hands (official pipeline, this machine)\n")
    ship = yload(RUNS / "armF_shipped" / "summary.yaml"); pinch = yload(RUNS / "armF_pinch" / "summary.yaml"); noadv = yload(RUNS / "armF_noadvance" / "summary.yaml")
    if ship or pinch:
        names = sorted(PUB)
        def col(d, n, k):
            if not d: return None
            m = {r["robot"]: r for r in d["rows"]}
            return m.get(n, {}).get(k)
        out.append("| hand | published T | shipped T (here) | pinch-only L_ref T | no-advance T | published R | pinch R |")
        out.append("|---|---|---|---|---|---|---|")
        for n in names:
            out.append(f"| {n} | {PUB[n]['KaRMA_T']:.5f} | {fmt(col(ship, n, 'KaRMA_T'), 5)} | {fmt(col(pinch, n, 'KaRMA_T'), 5)} | "
                       f"{fmt(col(noadv, n, 'KaRMA_T'), 5)} | {PUB[n]['KaRMA_R']:.4f} | {fmt(col(pinch, n, 'KaRMA_R'))} |")
        from scipy.stats import spearmanr
        for label, d in (("shipped (this machine)", ship), ("pinch-only", pinch)):
            if d and len(d["rows"]) >= 3:
                ok = [r for r in d["rows"] if "error" not in r]
                a = np.array([PUB[r["robot"]]["KaRMA_T"] for r in ok]); bb = np.array([r["KaRMA_T"] for r in ok])
                inv = sum(1 for i in range(len(ok)) for j in range(i + 1, len(ok)) if (a[i] - a[j]) * (bb[i] - bb[j]) < 0)
                out.append(f"\n{label} vs published KaRMA-T ranking over {len(ok)} hands: Spearman rho = {spearmanr(a, bb).correlation:.3f}, pairwise inversions = {inv}")
    else:
        out.append("(pending)")

    # exploit
    ex = jload(RUNS / "exploit_stubs" / "summary.json")
    if ex:
        a_, b_ = ex["two_finger"], ex["with_stubs"]
        out.append(f"\n## Stub-finger degeneracy (proxy)\n\nBaseline hand: L_ref {a_['lref']['L_ref_m']*1e3:.1f} mm, proxy T {a_['proxy']['karma_t']:.4f}. "
                   f"With 3 x 11 mm stubs: L_ref {b_['lref']['L_ref_m']*1e3:.1f} mm, proxy T >= {b_['proxy']['karma_t']:.3f} "
                   f"(capped at {b_['proxy']['top3_voxels'][0]} voxels): inflation >= x{b_['proxy']['karma_t']/a_['proxy']['karma_t']:.0f}.\n")

    # audit
    ap = RUNS / "audit_A1" / "audit.jsonl"
    if not ap.exists():
        ap = RUNS / "audit_T" / "audit.jsonl"
    if ap.exists():
        rows_a = [json.loads(l) for l in ap.read_text().splitlines() if l.strip()]
        if len(rows_a) >= 3:
            from scipy.stats import spearmanr
            p = np.array([r["proxy_T"] for r in rows_a]); o = np.array([r["official_T"] for r in rows_a])
            out.append(f"\n## Proxy audit ({ap.parent.name})\n\n{len(rows_a)} designs official-scored: Spearman rho(proxy, official) = {spearmanr(p, o).correlation:.3f}, "
                       f"median official/proxy = {np.median(o/np.maximum(p,1e-9)):.2f}, top-5 agreement = {len(set(np.argsort(-p)[:5]) & set(np.argsort(-o)[:5]))}/5.\n")
            out.append("| design | proxy T | official T | official R | official S | official voxels |")
            out.append("|---|---|---|---|---|---|")
            for r in sorted(rows_a, key=lambda r: -r["official_T"]):
                out.append(f"| {r['key']} | {r['proxy_T']:.4f} | {r['official_T']:.4f} | {r['official_R']:.3f} | {fmt(r['official_S'], 3)} | {r['official_voxels']} |")

    # arm E
    for tag in ("r006", "r016"):
        d = yload(RUNS / f"armE_{tag}" / "summary.yaml")
        if d:
            out.append(f"\n## Arm E: sphere radius {tag[1:]}/1000 of nominal scale ({d['rows'][0].get('sphere_radius_mm', '?')} mm at this hand's L_ref for the first row)\n")
            out.append("| hand | T at nominal radius | T here | R nominal | R here |")
            out.append("|---|---|---|---|---|")
            for r in d["rows"]:
                n = r["robot"]
                nomT = PUB[n]["KaRMA_T"] if n in PUB else (jload(RUNS / n[4:] / "final" / "summary.json") or {}).get("KaRMA_T")
                nomR = PUB[n]["KaRMA_R"] if n in PUB else (jload(RUNS / n[4:] / "final" / "summary.json") or {}).get("KaRMA_R")
                out.append(f"| {n} | {fmt(nomT, 5)} | {fmt(r.get('KaRMA_T'), 5)} | {fmt(nomR)} | {fmt(r.get('KaRMA_R'))} |")

    # features
    fp = RUNS / "features.csv"
    if fp.exists():
        rows_f = list(csv.DictReader(open(fp)))
        keys = [k for k in rows_f[0] if k not in ("hand", "kind", "KaRMA_T", "KaRMA_R")]
        out.append("\n## Kinematic features: published hands vs optimized designs\n")
        out.append("rho = Spearman correlation of the feature with official KaRMA-T across the 16 published hands.\n")
        out.append("| feature | rho(T) | published median [min, max] | " + " | ".join(r["hand"] for r in rows_f if r["kind"] == "optimized") + " |")
        out.append("|---|---|---|" + "---|" * sum(1 for r in rows_f if r["kind"] == "optimized"))
        from scipy.stats import spearmanr
        pubr = [r for r in rows_f if r["kind"] == "published"]; T = np.array([float(r["KaRMA_T"]) for r in pubr])
        for k in keys:
            v = np.array([float(r[k]) for r in pubr]); ok = np.isfinite(v)
            rho = spearmanr(v[ok], T[ok]).correlation
            opt = " | ".join(f"{float(r[k]):.2f}" for r in rows_f if r["kind"] == "optimized")
            out.append(f"| {k} | {rho:.2f} | {np.nanmedian(v):.2f} [{np.nanmin(v):.2f}, {np.nanmax(v):.2f}] | {opt} |")

    (RUNS / "RESULTS_AUTO.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
