"""Rebuild ``scores.yaml`` from the original result files (Phase 0 baseline freeze).

    python -m dkarma.fixtures.freeze            # rewrites dkarma/fixtures/scores.yaml

Sources (all read-only; ``results/all_hands_*.yaml`` is gitignored, so its
rows are copied into ``scores.yaml`` rather than referenced):

* reference backend, 16 shipped hands: ``results/16_hand_batch/summary.yaml``
  (the paper's table; 32-thread i9-13900KS, 2026-07-01).
* JAX fp32 backend, 16 shipped hands: ``results/all_hands_20261010_182148.yaml``
  (warm-cache sweep on this machine's RTX 4090, 2026-10-10; voxel counts
  identical to the cold sweep ``..._181104.yaml``).
* optimizer designs: ``optimize/runs/baseline/summary.json`` (reference),
  ``optimize/runs/T/final/summary.json`` (reference),
  ``optimize/runs/A1/final/summary.json`` (JAX fp32) and, once the queued job
  has produced it, ``optimize/runs/A1/final_reference/summary.json``.

Entries recorded later by ``rescore.py --record`` are kept (they live under
``recorded.<backend>`` keys this script does not write, or are re-read from
the existing file when the original source is missing).
"""
from __future__ import annotations

import glob
import json
import sys
from pathlib import Path

import yaml

from . import ROOT, SCORES_PATH, SCORE_FIELDS

PAPER = ROOT / "results" / "16_hand_batch" / "summary.yaml"
JAX_SWEEP = ROOT / "results" / "all_hands_20261010_182148.yaml"
THIS_MACHINE_CPU = "AMD EPYC-Milan (12 cores)"
THIS_MACHINE_GPU = "NVIDIA GeForce RTX 4090 + " + THIS_MACHINE_CPU

HEADER = """\
# Phase 0 regression fixtures (SPEC.md section 11): recorded exact KaRMA scores
# for the 16 shipped hands and the three optimizer designs (baseline, T, A1).
# Generated by `python -m dkarma.fixtures.freeze` from the result files named in
# each `source`; `python -m dkarma.fixtures.rescore --record` adds new records.
# Tolerance levels are documented in dkarma/fixtures/__init__.py (TOLERANCES).
# A `null` record means "not yet recorded under that backend".
"""

EXTRA_FIELDS = ("L_ref_mm", "ensemble_t", "ensemble_r", "runtime_s")


def _row(src: dict, source: str, machine: str, date: str, code: str, extra: dict | None = None) -> dict:
    out = {"source": source, "machine": machine, "date": date, "code": code}
    if extra:
        out.update(extra)
    for f in SCORE_FIELDS + EXTRA_FIELDS:
        if f in src and src[f] is not None:
            out[f] = src[f]
    return out


def build() -> dict:
    existing = yaml.safe_load(SCORES_PATH.read_text()) if SCORES_PATH.exists() else {"fixtures": {}}
    fixtures: dict[str, dict] = {}

    # shipped hands
    paper = yaml.safe_load(PAPER.read_text())
    pm = paper["machine"]
    paper_machine = f"{pm['cpu']} ({pm['cpu_count']} threads), {pm['platform']}"
    paper_rows = {r["robot"]: r for r in paper["rows"]}
    jax_rows = {}
    if JAX_SWEEP.exists():
        jax_rows = {r["robot"]: r for r in yaml.safe_load(JAX_SWEEP.read_text())["rows"]}
    for p in sorted(glob.glob(str(ROOT / "robots" / "robot_*.yaml"))):
        name = Path(p).stem.replace("robot_", "")
        if name == "template":
            continue
        rec = {}
        if name in paper_rows:
            rec["reference"] = _row(paper_rows[name], "results/16_hand_batch/summary.yaml", paper_machine,
                                    str(paper["timestamp"])[:10], "paper release c8d3698 (reference backend)")
        old = (existing["fixtures"].get(name, {}).get("recorded") or {}).get("jax_fp32")
        if old and str(old.get("date", "")) > "2026-10-10":
            rec["jax_fp32"] = old          # a later `rescore --record` entry wins over the original sweep
        elif name in jax_rows:
            rec["jax_fp32"] = _row(jax_rows[name], "results/all_hands_20261010_182148.yaml (gitignored; copied)",
                                   THIS_MACHINE_GPU, "2026-10-10",
                                   "karma_jax Phase D, exact padding, before the Phase 0 padding fixes "
                                   "(bitwise unaffected by them)")
        else:
            rec["jax_fp32"] = old
        fixtures[name] = {"kind": "shipped", "robot_yaml": f"robots/robot_{name}.yaml", "recorded": rec}

    # optimizer designs
    designs = {
        "baseline": ("baseline_hand", {"reference": ("optimize/runs/baseline/summary.json", THIS_MACHINE_CPU, "2026-10-09",
                                                     "reference backend, optimize/evaluate_full.py")},
                     "anthropomorphic start of the 4+4 family (HandFamily.anthropomorphic_x0)"),
        "T": ("opt_T", {"reference": ("optimize/runs/T/final/summary.json", THIS_MACHINE_CPU, "2026-10-10",
                                      "reference backend, optimize/evaluate_full.py (12 rotation workers)")},
              "run-T winner (KaRMA-T 0.575, the metric exploit of optimize/runs/REPORT.md)"),
        "A1": ("opt_A1", {"jax_fp32": ("optimize/runs/A1/final/summary.json", THIS_MACHINE_GPU, "2026-10-10",
                                       "karma_jax fp32 search, exact padding (J_pad = n_joints + 1 workaround "
                                       "at the time; bitwise identical to exact padding)"),
                          "reference": ("optimize/runs/A1/final_reference/summary.json", THIS_MACHINE_CPU, None,
                                        "reference backend, queued (optimize/queue.txt)")},
               "run-A1 winner (GPU restart of run T, KaRMA-T 0.449)"),
    }
    for name, (robot, srcs, note) in designs.items():
        rec = {}
        for backend, (src, machine, date, code) in srcs.items():
            path = ROOT / src
            if path.exists():
                d = json.loads(path.read_text())
                if backend == "jax_fp32":
                    assert d.get("backend", "").startswith("jax"), (name, d.get("backend"))
                rec[backend] = _row(d, src, machine, date or "", code,
                                    {"mxPr_mm": d.get("mxPr_mm"), "mF_mm": d.get("mF_mm"),
                                     "sphere_radius_mm": d.get("sphere_radius_mm")})
            else:
                rec[backend] = (existing["fixtures"].get(name, {}).get("recorded") or {}).get(backend)
        for backend in ("reference", "jax_fp32"):
            rec.setdefault(backend, (existing["fixtures"].get(name, {}).get("recorded") or {}).get(backend))
        fixtures[name] = {"kind": "design", "robot_yaml": f"dkarma/fixtures/designs/{name}/robot_{robot}.yaml",
                          "design_json": f"dkarma/fixtures/designs/{name}/{robot}.json",
                          "copied_from": "optimize/runs/baseline" if name == "baseline" else f"optimize/runs/{name}/final",
                          "note": note, "recorded": rec}
        # keep any other recorded backends from the existing file
        for k, v in (existing["fixtures"].get(name, {}).get("recorded") or {}).items():
            rec.setdefault(k, v)

    return {"generated_by": "python -m dkarma.fixtures.freeze", "fixtures": fixtures}


def main() -> None:
    data = build()
    SCORES_PATH.write_text(HEADER + yaml.safe_dump(data, sort_keys=False, default_flow_style=None, width=100))
    n_ref = sum(1 for f in data["fixtures"].values() if f["recorded"].get("reference"))
    n_jax = sum(1 for f in data["fixtures"].values() if f["recorded"].get("jax_fp32"))
    print(f"wrote {SCORES_PATH.relative_to(ROOT)}: {len(data['fixtures'])} fixtures, "
          f"{n_ref} with reference records, {n_jax} with jax_fp32 records")


if __name__ == "__main__":
    sys.exit(main())
